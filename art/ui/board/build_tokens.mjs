// Writes art/ui/board/tokens.css from client/ui/tokens.json, so the style
// board paints with the client's own colours and gradients and names no
// value of its own. `--check` fails if tokens.css is out of date.
//
//   node art/ui/board/build_tokens.mjs           rewrite tokens.css
//   node art/ui/board/build_tokens.mjs --check   exit 1 if it would change
//
// --c-<name>   a colour token (tokens.json "color")
// --hc-<name>  its high-contrast value ("color_high_contrast"), when it has one
// --g-<name>   a gradient ("gradient"), its stops resolved to colours
// --m-<material>-<part>        a material's colour for that part (line, rim,
//                              highlight, shade, drop, soft, glow), and
// --m-<material>-<part>-w      its width in points (soft: -y and -blur too)
// --d-<name>   a colour the design document states that tokens.json does not
//              carry; each names its section, and check_board.mjs confirms
//              the hex is written there.
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const tokens = JSON.parse(readFileSync(join(root, 'client/ui/tokens.json'), 'utf8'));

// The world behind the HUD: §21.8 checks it over §21.2's day, dusk and night
// skies. The day sky is a token (sky_top, sky_bottom); dusk and night are not.
export const DESIGN = {
  sky_dusk_top: ['#6A4FC9', '21.2'],
  sky_dusk_bottom: ['#F29C7B', '21.2'],
  sky_night_top: ['#1A1433', '21.2'],
  sky_night_bottom: ['#3A2B6B', '21.2'],
};

const kebab = (s) => s.replace(/_/g, '-');
const colour = (ref) => {
  if (ref.startsWith('#')) return ref.toUpperCase();
  const c = tokens.color[ref];
  if (!c) throw new Error(`gradient names an unknown colour token: ${ref}`);
  return `var(--c-${kebab(ref)})`;
};

function gradient(g) {
  const stops = g.value.map(([at, ref]) => `${colour(ref)} ${+(at * 100).toFixed(2)}%`).join(', ');
  if (g.conic_from !== undefined) return `conic-gradient(from ${g.conic_from}deg, ${stops})`;
  if (g.radial) {
    const [cx, cy] = g.radial;
    return `radial-gradient(circle at ${+(cx * 100).toFixed(2)}% ${+(cy * 100).toFixed(2)}%, ${stops})`;
  }
  return `linear-gradient(${g.angle ?? 180}deg, ${stops})`;
}

export function build() {
  const lines = [
    '/* Generated by art/ui/board/build_tokens.mjs from client/ui/tokens.json. Do not edit. */',
    ':root {',
  ];
  for (const [name, c] of Object.entries(tokens.color)) {
    if (name.startsWith('_')) continue;
    lines.push(`  --c-${kebab(name)}: ${c.value.toUpperCase()};`);
  }
  for (const [name, c] of Object.entries(tokens.color_high_contrast)) {
    if (name.startsWith('_')) continue;
    lines.push(`  --hc-${kebab(name)}: ${c.value.toUpperCase()};`);
  }
  for (const [name, g] of Object.entries(tokens.gradient)) {
    if (name.startsWith('_')) continue;
    lines.push(`  --g-${kebab(name)}: ${gradient(g)};`);
  }
  for (const [name, m] of Object.entries(tokens.material)) {
    if (name.startsWith('_') || typeof m !== 'object') continue;
    const n = kebab(name);
    for (const part of ['line', 'rim', 'rim_2', 'highlight', 'shade', 'drop', 'soft', 'glow']) {
      if (!Array.isArray(m[part])) continue;
      const [ref, w, blur] = m[part];
      const p = kebab(part);
      lines.push(`  --m-${n}-${p}: ${colour(ref)};`);
      if (part === 'soft') {
        lines.push(`  --m-${n}-${p}-y: ${w}px;`, `  --m-${n}-${p}-blur: ${blur}px;`);
      } else {
        lines.push(`  --m-${n}-${p}-w: ${w}px;`);
      }
    }
    if (m.gloss !== undefined) lines.push(`  --m-${n}-gloss: ${m.gloss};`);
    if (m.radius !== undefined) lines.push(`  --m-${n}-radius: ${m.radius}px;`);
  }
  for (const [name, [hex, section]] of Object.entries(DESIGN)) {
    lines.push(`  --d-${kebab(name)}: ${hex}; /* §${section} */`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

// Run as a script: compare real paths, not a file:// URL, which
// percent-encodes a space that argv keeps (FX1-T-06). Node loads the main
// module from its real path, so argv's is resolved the same way.
if (process.argv[1] && fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  const out = join(here, 'tokens.css');
  const css = build();
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(out, 'utf8'); } catch {}
    if (now !== css) {
      console.error('art/ui/board/tokens.css is out of date: run node art/ui/board/build_tokens.mjs');
      process.exit(1);
    }
    console.log('tokens.css is up to date');
  } else {
    writeFileSync(out, css);
    console.log(`wrote ${out}`);
  }
}
