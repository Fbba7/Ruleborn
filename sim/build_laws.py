#!/usr/bin/env python3
"""Generate src/laws_table.rs from content/law_effects.json.

    python3 sim/build_laws.py            # write it
    python3 sim/build_laws.py --check    # fail if the committed file differs

The simulation cannot read JSON — it has no dependencies and decides nothing
in decimals (§24.7) — so the laws reach it as a table of exact ratios,
generated here and committed, the same way the sine table is. `--check` is
what keeps the committed table from drifting from the content file: the
content gate runs it.

Every value becomes numerator/denominator over 1000, reduced, so 1.25 is 5/4
and 0.65 is 13/20. A value that is not a whole number of thousandths is
refused rather than rounded: rounding would be the table deciding a number
the content file did not.
"""

import json
import math
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
CONTENT = HERE.parent / "content" / "law_effects.json"
OUT = HERE / "src" / "laws_table.rs"


def ratio(value) -> tuple[int, int]:
    scaled = value * 1000
    if abs(scaled - round(scaled)) > 1e-9:
        raise SystemExit(f"{value} is not a whole number of thousandths")
    num, den = round(scaled), 1000
    g = math.gcd(num, den) or 1
    return num // g, den // g


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def render() -> str:
    data = json.loads(CONTENT.read_text(encoding="utf-8"))
    params = data["_rule_sheet"]
    lines = [
        "//! Generated by `sim/build_laws.py` from `content/law_effects.json`.",
        "//! Do not edit: change the content file and regenerate. The content",
        "//! gate fails if this differs from what the generator would write.",
        "",
        "/// §12.21's rule sheet: every parameter a law may set.",
        "#[derive(Clone, Copy, PartialEq, Eq, Debug)]",
        "pub enum Param {",
    ]
    lines += [f"    {camel(p)}," for p in params]
    lines += [
        "}",
        "",
        "/// One of §7's laws: what it sets, as exact ratios, and whether its whole",
        "/// effect is a parameter change (`tools/law_effects.py`'s classification).",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct LawDef {",
        "    pub id: &'static str,",
        "    pub name: &'static str,",
        "    pub simulated: bool,",
        "    pub params: &'static [(Param, i64, i64)],",
        "}",
        "",
        f"pub const LAWS: [LawDef; {len(data['laws'])}] = [",
    ]
    for law in data["laws"]:
        ps = ", ".join(f"(Param::{camel(k)}, {n}, {d})"
                       for k, v in law["params"].items() for n, d in [ratio(v)])
        lines.append(f"    LawDef {{ id: \"{law['id']}\", name: \"{law['name']}\", "
                     f"simulated: {'true' if law['simulated'] else 'false'}, "
                     f"params: &[{ps}] }},")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("sim/src/laws_table.rs differs from content/law_effects.json: "
                  "run python3 sim/build_laws.py")
            return 1
        print("laws table matches content/law_effects.json")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(HERE.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
