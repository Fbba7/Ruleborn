#!/usr/bin/env python3
"""Generate src/sin_table.rs: a quarter turn of sine in Fx (32 fractional bits).

    python3 sim/build_table.py

Why a generator and not a constant computed at start-up
-------------------------------------------------------
§24.7 forbids floating point inside the simulation. A table computed when the
program starts would need `sin()` from libm, which is exactly the kind of
function that differs between platforms — glibc, musl and a browser's runtime
do not agree on the last bit, and the last bit is what a checksum reads.

So the table is computed once, here, by Python's `decimal` at 60 digits, and
checked in as integers. This script never runs inside the game. It is run when
the table's size changes and its output is committed, which is the same rule
§31.4 applies to the document's generated tables.
"""

import decimal
import pathlib

decimal.getcontext().prec = 60
D = decimal.Decimal

#: Where a series is small enough to stop. Decimal has no underflow: a term
#: shrinks forever without ever becoming exactly zero, so `while term != 0`
#: never ends. Every series here stops at the precision it is computed to.
TINY = D(10) ** -55

STEPS = 1024          # entries across a quarter turn, plus the endpoint
FX_BITS = 32


def pi() -> D:
    """π to the current precision, by the Chudnovsky-free Machin formula.

    Machin is enough here and is short: π/4 = 4·atan(1/5) − atan(1/239).
    """
    def atan_inv(x: int) -> D:
        # atan(1/x) = 1/x - 1/(3x^3) + 1/(5x^5) - ...
        total, term, n = D(0), D(1) / D(x), 0
        while abs(term) > TINY:
            total += term / (2 * n + 1) * (-1 if n % 2 else 1)
            n += 1
            term /= D(x * x)
        return total
    return 4 * (4 * atan_inv(5) - atan_inv(239))


def sin(x: D) -> D:
    """sin by Taylor series; x is small (at most π/2) so this converges fast."""
    total, term, n = D(0), x, 0
    while abs(term) > TINY:
        total += term
        n += 1
        term = -term * x * x / D((2 * n) * (2 * n + 1))
    return total


def main() -> int:
    half_pi = pi() / 2
    one = D(2) ** FX_BITS
    values = []
    for i in range(STEPS + 1):
        angle = half_pi * D(i) / D(STEPS)
        # Round half to even on the exact decimal, so the table does not lean.
        v = (sin(angle) * one).quantize(D(1), rounding=decimal.ROUND_HALF_EVEN)
        values.append(int(v))
    assert values[0] == 0, values[0]
    assert values[-1] == int(one), values[-1]

    out = pathlib.Path(__file__).resolve().parent / "src" / "sin_table.rs"
    lines = [
        "// Generated by sim/build_table.py — do not edit.",
        "//",
        "// A quarter turn of sine at 32 fractional bits, computed in exact",
        "// decimal arithmetic and checked in, because §24.7 forbids floating",
        "// point inside the simulation and libm does not agree with itself",
        "// across platforms.",
        f"pub const SIN_TABLE: [i64; {len(values)}] = [",
    ]
    for i in range(0, len(values), 6):
        lines.append("    " + " ".join(f"{v}," for v in values[i:i + 6]))
    lines.append("];")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out} — {len(values)} entries, endpoint {values[-1]} == 1.0")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
