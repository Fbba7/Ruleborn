    for level, published in zip((2, 3, 4, 5), (17, 46, 104, 155)):
        lines.append(f"| {level} | Day {published} | "
                     f"{cell('engaged', lambda r, lv=level: r.day(f'A realm at level {lv}'))} |")
    lines += ["", "| Day | §5.5 capacity | The run |", "| --- | --- | --- |"]
