        "them last. No choice here is the document's to guess: each is one sentence "
        "in §14.1 when it decides.",
        "",
        "## What the run does not carry",
        "",
        *[f"- {item}" for item in NOT_MODELLED],
        "",
        "Each would move a day, and none is guessed into the tables.",
        "",
        "Reproduce: `python3 -m tools.economy_model rerun`; the tables are "
        "`tools/economy_model/rerun.py` under `Config.document()`.",
