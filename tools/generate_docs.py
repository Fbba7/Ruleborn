#!/usr/bin/env python3
"""Generate the design document's summary tables from the content data.

    python3 tools/generate_docs.py           # write them
    python3 tools/generate_docs.py --check   # fail if they have drifted

Four of the register's contradictions — C1, C3, C6, C19 — have the same cause:
the same facts were written down twice by hand, and one copy was updated. The
structural fix is that a summary table is never authored, only emitted.

So the tables that exist purely to summarise something else become build
artifacts:

  §11.2's roster index      <- content/ruleborn.json
  §7.4's law summary        <- content/laws.json
  §29.1's formulas appendix <- content/detection.json + the economy constants

`--check` regenerates into memory and compares, so a hand edit fails the build
instead of surviving to the next version. That is the same guarantee §24.9 asks
for on content, applied to prose.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
OUT = ROOT / "docs" / "design" / "generated"

sys.path.insert(0, str(ROOT))
from tools.economy_model import data as econ                        # noqa: E402

BANNER = ("<!-- GENERATED by tools/generate_docs.py from content/. "
          "Do not edit: run the generator. -->\n")


def load(name: str) -> list | dict:
    return json.loads((CONTENT / f"{name}.json").read_text(encoding="utf-8"))


def row(*cells) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |\n"


# ---------------------------------------------------------------------------

def roster() -> str:
    """The §11.2 index. Under C6 this is emitted, never hand-maintained."""
    creatures = load("ruleborn")
    out = [BANNER, "# The eighteen ruleborn — index\n\n",
           "Generated from `content/ruleborn.json`. This replaces §11.2, which the\n",
           "design document maintains by hand alongside §11.11's full sheets — the\n",
           "two drifted into different creatures, which is contradiction C6.\n\n",
           "The full sheets stay in §11.11 and remain the source. This table exists\n",
           "only to be scanned.\n\n"]
    out.append(row("Ruleborn", "School", "Role", "Ability", "Resists"))
    out.append(row("---", "---", "---", "---", "---"))
    for c in sorted(creatures, key=lambda c: (
            ["Motion", "Matter", "Time", "Energy", "Life", "Spirit"].index(c["school"]),
            c["name"])):
        flag = " ⚠" if c.get("conflict_severity") == "role" else ""
        out.append(row(c["name"] + flag, c["school"], c["role"],
                       c.get("ability", "—"), c.get("resists", "—")))
    conflicts = [c for c in creatures if c.get("conflict_severity") == "role"]
    if conflicts:
        out.append("\n⚠ marks a creature whose role §11.2 and §11.11 disagree on "
                   "(C6, unresolved):\n\n")
        for c in conflicts:
            out.append(f"- **{c['name']}** — §11.11 says {c['role']}, "
                       f"§11.2 says {c['alt_11_2']['role']}\n")
    return "".join(out)


def law_summary() -> str:
    """The §7.4 summary. The full sheets in §7.7 stay the source."""
    laws = load("laws")
    schools = ["Motion", "Matter", "Time", "Energy", "Life", "Spirit"]
    boosts = {"Motion": "Starlight", "Matter": "Starlight", "Time": "Aether",
              "Energy": "Aether", "Life": "Essence", "Spirit": "Essence"}
    shapes = {"Motion": "chevron", "Matter": "cube", "Time": "hourglass",
              "Energy": "bolt", "Life": "leaf", "Spirit": "eye"}
    out = [BANNER, "# The 48 laws — summary\n\n",
           "Generated from `content/laws.json`, which is extracted from §7.7's full\n",
           "sheets. This replaces §7.4, whose rank column is the one the five-rank\n",
           "prose in §7.10 contradicts (C3).\n\n"]
    for school in schools:
        rows = [law for law in laws if law["school"] == school]
        out.append(f"## {school}\n\nShape: {shapes[school]}. Boosts {boosts[school]}.\n\n")
        out.append(row("Law", "Rank, cost", "Notes", "Effect at tier I",
                       "Tiers II and III", "How characters move"))
        out.append(row("---", "---", "---", "---", "---", "---"))
        for law in rows:
            out.append(row(law["name"], f"{law['rank']}, {law['stability_cost']}",
                           " ".join(law["notes"]), law["tier_1"],
                           law["tiers_2_3"], law["movement"]))
        out.append("\n")
    return "".join(out)


def formulas() -> str:
    """The §29.1 appendix.

    §29.1 currently encodes the SUPERSEDED detection model (C1) — the worst
    place for a stale number, because it is where an implementer looks. Emitting
    it from content/detection.json makes that impossible.
    """
    det = load("detection")
    sus = det["suspicion"]
    tps = det["_tick_rate"]

    out = [BANNER, "# Formulas\n\n",
           "Generated from `content/detection.json` and the economy constants in\n",
           "`tools/economy_model/data.py`. This replaces §29.1, which still carries\n",
           "the detection model §12.17 superseded (C1) — the worst place for a stale\n",
           "number, since it is where an implementer looks for it.\n\n"]

    out.append("## Detection (§12.17)\n\n")
    out.append(row("What", "Formula"))
    out.append(row("---", "---"))
    out.append(row("Tick rate", f"{tps} a second, fixed (§24.10)"))
    out.append(row("Suspicion", f"0 to {sus['max']}, per guard"))
    for zone in ("near", "mid", "far"):
        out.append(row(f"Fill, {zone} zone",
                       f"{sus['fill_per_tick'][zone]} a tick "
                       f"(~{sus['fill_seconds'][zone]} s to full)"))
    out.append(row("Decay", f"{sus['decay_per_tick']} a tick "
                            f"(~{sus['decay_seconds']} s from full)"))
    out.append(row("State floor", f"{sus['state_floor_ticks']} ticks before a state may fall back"))
    thresholds = ", ".join(f"{s['id'].capitalize()} {s['at']}"
                           for s in det["states"] if s["at"] is not None)
    out.append(row("States", thresholds))
    out.append(row("Alarm spread",
                   f"guards within {det['alarm']['spread_radius_m']} m, "
                   f"{det['alarm']['spread_delay_ticks']} ticks later"))
    out.append(row("Realm alarm",
                   f"0 to {det['alarm']['realm_alarm_max']}; "
                   f"+1 per 30 s and +1 per guard found; "
                   f"reinforcement at {det['alarm']['reinforcement_at']}"))
    amb = det["ambush"]
    out.append(row("Ambush", f"first unseen hit: {amb['stun_seconds']} s stun and "
                             f"{amb['damage_multiplier']}x damage; "
                             f"level advantage counts for at most "
                             f"{amb['level_advantage_cap']} levels"))
    out.append("\n### Guard vision\n\n")
    out.append(row("Guard", "Cone", "Near", "Mid", "Far", "Corner of the eye", "Turn"))
    out.append(row("---", "---", "---", "---", "---", "---", "---"))
    for g in det["guards"]:
        far = f"{g['far_m']} m" if g["far_m"] is not None else "—"
        out.append(row(g["role"], f"{g['cone_degrees']}°", f"{g['near_m']} m",
                       f"{g['mid_m']} m", far, f"{g['peripheral_degrees']}°",
                       f"{g['turn_degrees_per_tick']}°/tick"))
    out.append("\n### Noise\n\n")
    out.append(row("Action", "Heard within"))
    out.append(row("---", "---"))
    for n in det["noise"]["sources"]:
        heard = "silent" if n["heard_within_m"] == 0 else f"{n['heard_within_m']} m"
        out.append(row(n["id"].replace("_", " "), heard))
    out.append(f"\nSound travels along the walkable path, never through walls. "
               f"Guards off screen hear at "
               f"{det['noise']['off_screen_multiplier']:.0%} strength.\n")

    out.append("\n## Economy\n\n")
    out.append(row("What", "Formula", "Section"))
    out.append(row("---", "---", "---"))
    out.append(row("Stability capacity",
                   f"{econ.spire_stability(0)} + 8 x Spire level, plus every Anchor "
                   f"Stone ({econ.anchor_stability(0)} + 5 x its level)", "5.5"))
    bands = ", ".join(f"{b[2]} under {b[0]:.0%}" for b in econ.STRAIN_BANDS[:-1])
    out.append(row("Strain bands", bands + ", then Breaking", "5.5"))
    out.append(row("Production",
                   "base x 1.35^(level-1) x staffing x law bonuses x realm match "
                   "x worker bonuses x band bonus x faults", "9.3"))
    out.append(row("Staffing", " / ".join(f"{s:.0%}" for s in econ.STAFFING[1:]) +
                   " for one, two, three workers", "9.2"))
    out.append(row("Heist clock",
                   "150 s + 15 s per link on the shortest route, up to 240 s", "5.4"))
    out.append(row("Keeper curve",
                   "day ~ 0.13 x level^1.96 for an engaged player", "14.2"))
    out.append(row("Births", f"{econ.HAUL_BASE} x 1.15^(ruleborn owned) Essence", "9.5"))
    out.append(row("Haul", "see docs/design/spec/economy.md — C2 and C4 unresolved", "9.6"))
    return "".join(out)


def v3_response() -> str:
    """What version 3.0 did about each register item, emitted from the register.

    Written by a generator rather than by hand for the reason the register keeps
    finding: a summary of something else, authored separately, goes stale.
    """
    sys.path.insert(0, str(ROOT / "tools"))
    from audit_register import REGISTER, V3               # noqa: E402

    by_id = {i["id"]: i for i in REGISTER}
    fixed = [k for k, v in V3.items() if v.get("status") == "fixed"]
    moved = [k for k, v in V3.items() if v.get("status") != "fixed"]
    new = [i["id"] for i in REGISTER
           if i["id"] in ("C21", "C22", "C23", "C24", "C25", "C26",
                          "D19", "D20", "D21", "D22",
                          "F7", "F8", "F9", "F10", "F11", "F12")]

    def strip(html: str) -> str:
        import re as _re
        text = _re.sub(r"<br\s*/?>", " ", html)
        text = _re.sub(r"<[^>]+>", "", text)
        return " ".join(text.split())

    lines = [
        "<!-- GENERATED by tools/generate_docs.py — do not edit by hand -->",
        "",
        "# What version 3.0 did about the audit",
        "",
        "Emitted from `tools/audit_register.py`, so it cannot drift from the "
        "register the audit page shows.",
        "",
        f"v3.0 answered the audit directly, in §30.18. Of {len(REGISTER)} items, "
        f"**{len(fixed)} are fixed in the design document itself**, "
        f"{len(moved)} moved without being resolved, and {len(new)} are new. "
        "Six came from reading v3.0 the way v2.3 was read. The rest came from "
        "building the harnesses §19.27 now depends on, and from writing all 48 "
        "laws out against the rule sheet §7.3 claims they change.",
        "",
        "## Fixed in v3.0",
        "",
        "| | What it was | What v3.0 did |",
        "| --- | --- | --- |",
    ]
    for item_id in sorted(fixed, key=lambda k: (k[0], int(k[1:]))):
        lines.append(f"| **{item_id}** | {strip(by_id[item_id]['title'])} "
                     f"| {strip(V3[item_id]['note'])} |")

    lines += ["", "## Moved, but not resolved", "",
              "| | What it was | Where it stands |", "| --- | --- | --- |"]
    for item_id in sorted(moved, key=lambda k: (k[0], int(k[1:]))):
        lines.append(f"| **{item_id}** | {strip(by_id[item_id]['title'])} "
                     f"| {strip(V3[item_id]['note'])} |")

    lines += ["", "## Found in v3.0", "",
              "| | What it is |", "| --- | --- |"]
    for item_id in new:
        lines.append(f"| **{item_id}** | {strip(by_id[item_id]['title'])} |")

    lines += [
        "",
        "## The shape of it",
        "",
        "§30.18 draws the right conclusion from the v2.3 audit: *\"a table that "
        "exists only to summarise something else should be generated, never "
        "authored — four of the six conflicts had no other cause.\"*",
        "",
        "v3.0 then fixed six systems and left a stale copy of four of them. "
        "`tools/check_design_consistency.py` has a **Supersession** section that "
        "names each one and the exact sentence still carrying the old version; it "
        "fails until they are gone. The sharpest case is §29.1, the formulas "
        "appendix: it still tabulates the detection model §12.8 deleted, and cites "
        "§12.8 as its source.",
        "",
        "This file is generated for that reason.",
        "",
    ]
    return "\n".join(lines)


GENERATED = {
    "roster.md": roster,
    "laws.md": law_summary,
    "formulas.md": formulas,
    "v3-response.md": v3_response,
}


def main() -> int:
    check = "--check" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    drifted = []
    for name, fn in GENERATED.items():
        text = fn()
        path = OUT / name
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                drifted.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"  docs/design/generated/{name}  {len(text.splitlines())} lines")
    if check:
        if drifted:
            print("Generated docs have drifted from the data: "
                  + ", ".join(drifted), file=sys.stderr)
            print("Run: python3 tools/generate_docs.py", file=sys.stderr)
            return 1
        print("  generated docs are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
